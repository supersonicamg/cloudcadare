#!/usr/bin/env node
// Generates the typed feature and permission catalogs from the seed migration,
// so the SQL stays the single source of truth.
//   node packages/db/scripts/gen-catalogs.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const migDir = join(root, 'packages/db/supabase/migrations')
const seedFile = readdirSync(migDir).find((f) => f.endsWith('_99_seed_catalog.sql'))
const sql = readFileSync(join(migDir, seedFile), 'utf8')

/** Returns the VALUES tuples of the first `insert into <table> (...) values` statement. */
function tuples(table) {
  const start = sql.indexOf(`insert into ${table} `)
  if (start < 0) throw new Error(`insert into ${table} not found`)
  const values = sql.indexOf('values', start) + 'values'.length
  const rows = []
  let i = values, depth = 0, inStr = false, cur = ''
  for (; i < sql.length; i++) {
    const c = sql[i]
    if (!depth && !inStr && c === ';') break
    if (inStr) {
      cur += c
      if (c === "'" && sql[i + 1] === "'") { cur += "'"; i++ } else if (c === "'") inStr = false
      continue
    }
    if (c === '-' && sql[i + 1] === '-') { while (i < sql.length && sql[i] !== '\n') i++; continue }
    if (c === "'") { inStr = true; cur += c; continue }
    if (c === '(') { if (depth++ === 0) { cur = ''; continue } }
    if (c === ')') { if (--depth === 0) { rows.push(split(cur)); cur = ''; continue } }
    if (depth) cur += c
  }
  return rows
}

function split(row) {
  const out = []
  let cur = '', inStr = false, depth = 0
  for (let i = 0; i < row.length; i++) {
    const c = row[i]
    if (inStr) {
      if (c === "'" && row[i + 1] === "'") { cur += "'"; i++ } else if (c === "'") inStr = false
      else cur += c
      continue
    }
    if (c === "'") { inStr = true; continue }
    if (c === '(' || c === '{') depth++
    if (c === ')' || c === '}') depth--
    if (c === ',' && depth === 0) { out.push(cur.trim()); cur = ''; continue }
    cur += c
  }
  out.push(cur.trim())
  return out
}

const bool = (v) => v === 'true'
const num = (v) => (v === 'null' ? null : Number(v))
const arr = (v) => (v === '{}' ? [] : v.replace(/^\{|\}$/g, '').split(',').map((s) => s.trim()))

const features = tuples('control.features').filter((r) => r.length > 1).map((r) => ({
  key: r[0], module: r[1], name: r[2], kind: r[3], isCore: bool(r[4]),
  defaultEnabled: bool(r[5]), defaultLimit: num(r[6]), unit: r[7] === 'null' ? null : r[7],
  dependsOn: arr(r[8]), lifecycle: r[9], sortOrder: Number(r[10]),
}))
const permissions = tuples('public.permission_catalog').filter((r) => r.length > 1).map((r) => ({
  key: r[0], featureKey: r[1], group: r[2], description: r[3], sensitive: bool(r[4]),
}))

const header = `// GENERATED by packages/db/scripts/gen-catalogs.mjs from ${seedFile}. Do not edit.\n`
writeFileSync(join(root, 'packages/features/src/catalog.generated.ts'),
  `${header}export const FEATURES = ${JSON.stringify(features, null, 2)} as const\n\n` +
  `export type FeatureKey = (typeof FEATURES)[number]['key']\n` +
  `export type FeatureDef = (typeof FEATURES)[number]\n`)
writeFileSync(join(root, 'packages/permissions/src/catalog.generated.ts'),
  `${header}export const PERMISSIONS = ${JSON.stringify(permissions, null, 2)} as const\n\n` +
  `export type PermissionKey = (typeof PERMISSIONS)[number]['key']\n`)
console.log(`features: ${features.length}, permissions: ${permissions.length}`)
